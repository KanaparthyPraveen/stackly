import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { Document, HydratedDocument, Types } from 'mongoose';

export type MediaDocument = HydratedDocument<Media>;

export const MEDIA_TYPES = [
  'avatar',
  'cover',
  'project',
  'gallery',
  'resume',
  'document',
  'video',
] as const;

export type MediaType = (typeof MEDIA_TYPES)[number];

export const MEDIA_VISIBILITIES = ['public', 'private'] as const;
export type MediaVisibility = (typeof MEDIA_VISIBILITIES)[number];

/**
 * Metadata for a file held in object storage. The binary itself never
 * touches MongoDB — only its key, type, size and ownership.
 */
@Schema({
  timestamps: true,
  toJSON: {
    transform: (_doc, ret: Record<string, unknown>) => {
      delete ret.__v;
      return ret;
    },
  },
})
export class Media extends Document {
  @Prop({ type: Types.ObjectId, ref: 'User', required: true, index: true })
  userId: Types.ObjectId;

  /** Object key in the bucket. Always generated by the server. */
  @Prop({ required: true, unique: true, index: true })
  key: string;

  @Prop({ required: true })
  originalFilename: string;

  @Prop({ required: true })
  mimeType: string;

  @Prop({ required: true })
  sizeBytes: number;

  @Prop({ type: String, required: true, enum: MEDIA_TYPES })
  type: MediaType;

  /** Application path that serves the file (`/api/v1/media/public/<id>`). */
  @Prop({ required: true })
  url: string;

  /**
   * Who may fetch the file. Avatars, covers and gallery/project images are
   * public by default; resumes, documents and videos start private.
   * Documents written before this field existed fall back to the per-type
   * default.
   */
  @Prop({ type: String, enum: MEDIA_VISIBILITIES })
  visibility?: MediaVisibility;

  /**
   * False while a direct-to-storage upload has been authorised but not yet
   * confirmed. Unconfirmed records are never served and are cleaned up.
   */
  @Prop({ default: false })
  referenced: boolean;
}

export const MediaSchema = SchemaFactory.createForClass(Media);
MediaSchema.index({ userId: 1, type: 1 });
MediaSchema.index({ createdAt: 1, referenced: 1 });
