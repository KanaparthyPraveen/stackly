import { Injectable, Logger } from '@nestjs/common';
import * as fs from 'fs';
import * as path from 'path';

export interface StorageResult {
  key: string;
}

export interface StoredObjectMetadata {
  contentLength?: number;
  contentType?: string;
  lastModified?: Date;
  etag?: string;
}

/** What the media service needs from a storage backend. */
export interface IStorageProvider {
  save(key: string, buffer: Buffer, mimeType: string): Promise<StorageResult>;
  delete(key: string): Promise<void>;
  getMetadata(key: string): Promise<StoredObjectMetadata | null>;
  /** Reads the first `bytes` bytes of an object, for content sniffing. */
  readHead(key: string, bytes: number): Promise<Buffer | null>;
}

/**
 * Development fallback that keeps files on the local disk under `uploads/`.
 * Used only when no object storage credentials are configured.
 */
@Injectable()
export class LocalStorageProvider implements IStorageProvider {
  private readonly uploadDir: string;
  private readonly logger = new Logger(LocalStorageProvider.name);

  constructor() {
    this.uploadDir = path.resolve(process.cwd(), 'uploads');
    if (!fs.existsSync(this.uploadDir)) {
      fs.mkdirSync(this.uploadDir, { recursive: true });
    }
  }

  /**
   * Resolves a key to an absolute path and guarantees it stays inside the
   * upload directory. Keys are generated by the server, but this makes a
   * path-traversal bug elsewhere unable to escape the directory.
   */
  getFilePath(key: string): string {
    const resolved = path.resolve(this.uploadDir, key);
    if (
      resolved !== this.uploadDir &&
      !resolved.startsWith(this.uploadDir + path.sep)
    ) {
      throw new Error('Invalid storage key');
    }
    return resolved;
  }

  async save(key: string, buffer: Buffer): Promise<StorageResult> {
    const filePath = this.getFilePath(key);
    await fs.promises.mkdir(path.dirname(filePath), { recursive: true });
    await fs.promises.writeFile(filePath, buffer);
    return { key };
  }

  async delete(key: string): Promise<void> {
    try {
      await fs.promises.unlink(this.getFilePath(key));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'ENOENT') {
        this.logger.warn(
          `Could not delete file ${key}: ${(err as Error).message}`,
        );
      }
    }
  }

  async getMetadata(key: string): Promise<StoredObjectMetadata | null> {
    try {
      const stat = await fs.promises.stat(this.getFilePath(key));
      if (!stat.isFile()) return null;
      return { contentLength: stat.size, lastModified: stat.mtime };
    } catch {
      return null;
    }
  }

  async readHead(key: string, bytes: number): Promise<Buffer | null> {
    let handle: fs.promises.FileHandle | undefined;
    try {
      handle = await fs.promises.open(this.getFilePath(key), 'r');
      const buffer = Buffer.alloc(bytes);
      const { bytesRead } = await handle.read(buffer, 0, bytes, 0);
      return buffer.subarray(0, bytesRead);
    } catch {
      return null;
    } finally {
      await handle?.close();
    }
  }
}
